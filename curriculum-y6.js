    function convertDOMDigitsToWestern() {
        if (typeof RAW_YEAR !== 'undefined' && RAW_YEAR !== 6) return;
        const root = document.getElementById('main-content');
        if (!root) return;
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
        let node;
        while ((node = walker.nextNode())) {
            if (/[٠-٩]/.test(node.nodeValue)) {
                node.nodeValue = window.toWesternDigits(node.nodeValue);
            }
        }
    }

    function hookYear6Engine() {
        if (typeof RAW_YEAR === 'undefined' || RAW_YEAR !== 6) return;
        if (window._y6CleanHooked || typeof window.renderCurrentStep !== 'function') return;
        window._y6CleanHooked = true;
        document.body.classList.add('y6-mode-active');
        injectY6SentenceStyles();

        const origRender = window.renderCurrentStep;
        window.renderCurrentStep = function() {
            origRender.apply(this, arguments);
            convertDOMDigitsToWestern();
        };
    }

    if (document.readyState === 'loading') {
        window.addEventListener('DOMContentLoaded', hookYear6Engine);
    } else {
        setTimeout(hookYear6Engine, 0);
    }
