    function renderY3PocoyoStage(defData) {
        if (typeof RAW_YEAR !== 'undefined' && RAW_YEAR !== 3) return;
        injectY3PocoyoStyles();
        const isEdit = (typeof isSecretEditMode !== 'undefined' && isSecretEditMode);

        // 1. المحطة 1: مسرح بوكويو الأبيض المفرغ بلا أشرطة نصية
        if (globalStep === 1) {
            const slideObj = defData?.learn?.slides?.[0];
            if (!slideObj || !slideObj.pocoyoStage) return;

            const contentDiv = document.getElementById('main-content');
            const fancyCard = contentDiv ? contentDiv.querySelector('.fancy-card') : null;
            if (!fancyCard) return;

            const cfg = slideObj.pocoyoStage;
            window._activeSlideIdx = 0;

            fancyCard.innerHTML = `
                <div class="y3-pocoyo-layout">
                    <div class="y3-stage-split">
                        <div class="y3-art-frame">
                            <img src="${slideObj.img}" data-edit-asset-key="slide_img" alt="🌟">
                            <button type="button" class="y3-floating-speaker" id="y3-replay-btn" aria-label="استماع">🔊</button>
                        </div>
                        <div class="y3-white-canvas" id="y3-white-canvas">
                            ${cfg.letterBadge ? `<div class="y3-corner-letter">${cfg.letterBadge}</div>` : ''}
                        </div>
                    </div>
                </div>
            `;

            const canvas = document.getElementById('y3-white-canvas');
            const replayBtn = document.getElementById('y3-replay-btn');
            if (replayBtn) {
                replayBtn.onclick = (e) => {
                    e.stopPropagation();
                    if (typeof speakText === 'function') speakText(cfg.promptTTS || '');
                };
            }

            // أ) وضع العد البصري الحر (١ إلى ١٠) بدون نصوص أو أرقام كبيرة
            if (cfg.mode === 'count_to_10') {
                let currentCount = 0;
                const liveCounter = document.createElement('div');
                liveCounter.className = 'y3-ten-counter-pill';
                liveCounter.id = 'y3-live-count';
                liveCounter.innerText = '٠';
                canvas.appendChild(liveCounter);

                const grid = document.createElement('div');
                grid.className = 'y3-ten-grid';

                for (let i = 1; i <= 10; i++) {
                    const itemBtn = document.createElement('button');
                    itemBtn.type = 'button';
                    itemBtn.className = 'y3-ten-item';
                    itemBtn.innerHTML = `
                        <span>${cfg.tokenEmoji}</span>
                        <span class="y3-ten-num-badge">${ARABIC_DIGITS_10[i - 1]}</span>
                    `;
                    itemBtn.onclick = () => {
                        if (isEdit) return;
                        if (!itemBtn.classList.contains('counted-lit')) {
                            currentCount++;
                            itemBtn.classList.add('counted-lit');
                            const numSpan = itemBtn.querySelector('.y3-ten-num-badge');
                            if (numSpan) numSpan.innerText = ARABIC_DIGITS_10[currentCount - 1];
                        }
                        playChimeSafe();
                        const liveEl = document.getElementById('y3-live-count');
                        if (liveEl) liveEl.innerText = ARABIC_DIGITS_10[currentCount - 1];

                        const wordToSpeak = ARABIC_NUM_WORDS_10[Math.min(9, currentCount - 1)];
                        if (typeof speakText === 'function') {
                            speakText(wordToSpeak, () => {
                                if (currentCount >= 10) {
                                    playChimeSafe();
                                    updateNavButtons(true);
                                    showCenterAction(() => handleNextClick(), true);
                                }
                            });
                        }
                    };
                    grid.appendChild(itemBtn);
                }
                canvas.appendChild(grid);
            }
            // ب) وضع تقليد الأصوات بالحرف المفرد والحركات الثلاث (أَ أُ إِ)
            else if (cfg.mode === 'sound_imitation') {
                let touchedSet = new Set();

                const mainCharBtn = document.createElement('button');
                mainCharBtn.type = 'button';
                mainCharBtn.className = 'y3-pure-symbol';
                mainCharBtn.style.fontSize = 'clamp(4.6rem, 14vmin, 8rem)';
                mainCharBtn.innerHTML = cfg.mainSoundEmoji;
                mainCharBtn.onclick = () => {
                    if (isEdit) return;
                    touchedSet.add('main');
                    playChimeSafe();
                    if (typeof speakText === 'function') speakText(cfg.mainSoundSpeak || '');
                };
                canvas.appendChild(mainCharBtn);

                const harakatRow = document.createElement('div');
                harakatRow.style.cssText = 'display:flex; align-items:center; justify-content:center; gap:clamp(24px,5.5vmin,50px);';

                (cfg.harakatVoices || []).forEach((hv, idx) => {
                    const hBtn = document.createElement('button');
                    hBtn.type = 'button';
                    hBtn.className = 'y3-pure-symbol';
                    hBtn.style.cssText = 'display:flex; flex-direction:column; align-items:center; font-size:clamp(2.8rem,8vmin,4.6rem);';
                    hBtn.innerHTML = `
                        <span>${hv.face}</span>
                        <span style="font-size:0.85em; font-weight:900; color:#e11d48; margin-top:2px;">${typeof colorizeHarakaAndMadd === 'function' ? colorizeHarakaAndMadd(hv.glyph) : hv.glyph}</span>
                    `;
                    hBtn.onclick = () => {
                        if (isEdit) return;
                        touchedSet.add(idx);
                        if (typeof playEarTone === 'function') {
                            playEarTone(idx === 0 ? 'جَوَاب' : (idx === 1 ? 'وَسَط' : 'قَرَار'));
                        } else {
                            playChimeSafe();
                        }
                        if (typeof speakText === 'function') {
                            speakText(hv.speak || '', () => {
                                if (touchedSet.size >= 3) {
                                    playChimeSafe();
                                    updateNavButtons(true);
                                    showCenterAction(() => handleNextClick(), true);
                                }
                            });
                        }
                    };
                    harakatRow.appendChild(hBtn);
                });
                canvas.appendChild(harakatRow);
            }
            // ج) وضع تحريك الرموز المفرغة تماماً بدون أي نصوص تحتها
            else {
                const items = cfg.floatingItems || [];
                let doneCount = 0;

                const targetSpot = document.createElement('div');
                targetSpot.className = 'y3-pure-target-spot';
                targetSpot.innerHTML = `<div class="y3-pure-target-emoji" id="y3-target-emoji">${cfg.targetEmoji || '🌟'}</div>`;
                canvas.appendChild(targetSpot);

                const floatingRow = document.createElement('div');
                floatingRow.style.cssText = 'display:flex; align-items:center; justify-content:center; gap:clamp(30px,6.5vmin,60px); flex-wrap:wrap;';

                let activeDragBtn = null;
                let activeDragData = null;

                const triggerSymbolPlacement = (btn, itemData) => {
                    if (btn.classList.contains('moved-to-target')) return;
                    btn.classList.add('moved-to-target');
                    doneCount++;
                    playChimeSafe();
                    targetSpot.classList.add('active-glow');
                    const tEmoji = document.getElementById('y3-target-emoji');
                    if (tEmoji) tEmoji.innerText = itemData.emoji;

                    if (typeof speakText === 'function') {
                        speakText(itemData.speak || '', () => {
                            if (doneCount >= items.length) {
                                playChimeSafe();
                                updateNavButtons(true);
                                showCenterAction(() => handleNextClick(), true);
                            }
                        });
                    }
                };

                targetSpot.ondragover = (e) => { e.preventDefault(); targetSpot.classList.add('active-glow'); };
                targetSpot.ondrop = (e) => {
                    e.preventDefault();
                    if (activeDragBtn && activeDragData && !isEdit) {
                        triggerSymbolPlacement(activeDragBtn, activeDragData);
                    }
                };

                items.forEach((it) => {
                    const symBtn = document.createElement('button');
                    symBtn.type = 'button';
                    symBtn.className = 'y3-pure-symbol';
                    symBtn.draggable = !isEdit;
                    symBtn.innerHTML = it.emoji;

                    symBtn.ondragstart = () => { activeDragBtn = symBtn; activeDragData = it; };
                    symBtn.onclick = () => {
                        if (isEdit) return;
                        triggerSymbolPlacement(symBtn, it);
                    };
                    floatingRow.appendChild(symBtn);
                });

                canvas.appendChild(floatingRow);
            }

            if (isEdit && typeof attachEditHooksToCurrentStation === 'function') {
                attachEditHooksToCurrentStation(defData);
            }
        }
        // 2. المحطة 5: مشهد بوكويو الرمزي مع الحرف المفرد وزر الصوت فقط (بلا جمل مكتوبة)
        else if (globalStep === 5 && defData?.apply?.pocoyoScene) {
            const card = document.querySelector('.apply-structured-card');
            if (!card || card.querySelector('.y3-pocoyo-apply-theater')) return;

            const sc = defData.apply.pocoyoScene;
            const theaterBox = document.createElement('div');
            theaterBox.className = 'y3-pocoyo-apply-theater';
            theaterBox.innerHTML = `
                ${sc.letter ? `<span class="y3-apply-letter-badge">${typeof colorizeHarakaAndMadd === 'function' ? colorizeHarakaAndMadd(sc.letter) : sc.letter}</span>` : ''}
                <div class="y3-pocoyo-syms-strip">${sc.syms}</div>
                <span style="font-size:2rem;">🔊</span>
            `;
            theaterBox.onclick = () => {
                if (typeof speakText === 'function') speakText(sc.narratorTTS || '');
            };
            card.appendChild(theaterBox);
        }
    }

    // ربط المحرك وضبط المسار الثلاثي (0 -> 1 -> 5) لعمر 3 سنوات بأمان
    function hookYear3PocoyoEngine() {
        if (typeof RAW_YEAR === 'undefined' || RAW_YEAR !== 3) return;
        if (window._y3PocoyoHooked || typeof window.renderCurrentStep !== 'function') return;
        window._y3PocoyoHooked = true;
        document.body.classList.add('y3-clean-mode');
        injectY3PocoyoStyles();

        const origRender = window.renderCurrentStep;
        window.renderCurrentStep = function() {
            const isEdit = (typeof isSecretEditMode !== 'undefined' && isSecretEditMode);
            if (!isEdit && (globalStep === 2 || globalStep === 3 || globalStep === 4)) {
                globalStep = 5;
            }

            origRender.apply(this, arguments);

            [2, 3, 4].forEach(stIdx => {
                const dot = document.getElementById('dot-' + stIdx);
                if (dot && !isEdit) dot.classList.add('hidden-station');
            });

            const defData = (typeof getActiveCurriculumObj === 'function') ? getActiveCurriculumObj() : null;
            if (!defData) return;

            renderY3PocoyoStage(defData);

            if (globalStep === 0 && defData.learn?.introTTS && typeof speakText === 'function') {
                speakText(defData.learn.introTTS, () => {
                    if (typeof updateNavButtons === 'function') updateNavButtons(true);
                    if (typeof showCenterAction === 'function') showCenterAction(() => handleNextClick(), false);
                });
            } else if (globalStep === 1) {
                const promptTTS = defData.learn?.slides?.[0]?.pocoyoStage?.promptTTS;
                if (promptTTS && typeof speakText === 'function') speakText(promptTTS);
            } else if (globalStep === 5 && defData.apply?.pocoyoScene?.narratorTTS && typeof speakText === 'function') {
                speakText(defData.apply.pocoyoScene.narratorTTS, () => {
                    if (typeof updateNavButtons === 'function') updateNavButtons(true);
                    if (typeof showCenterAction === 'function') showCenterAction(() => completeLesson(activeViewSubj), true);
                });
            }
        };

        if (typeof window.handlePrevClick === 'function') {
            const origPrev = window.handlePrevClick;
            window.handlePrevClick = function() {
                const isEdit = (typeof isSecretEditMode !== 'undefined' && isSecretEditMode);
                if (!isEdit && globalStep === 5) {
                    if ('speechSynthesis' in window) window.speechSynthesis.cancel();
                    globalStep = 1;
                    window.renderCurrentStep();
                    return;
                }
                origPrev.apply(this, arguments);
            };
        }
    }

    if (document.readyState === 'loading') {
        window.addEventListener('DOMContentLoaded', hookYear3PocoyoEngine);
    } else {
        setTimeout(hookYear3PocoyoEngine, 0);
    }
