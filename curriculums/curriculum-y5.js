    function applyY5MetallicThemeForCurrentWeek() {
        if (typeof RAW_YEAR !== 'undefined' && RAW_YEAR !== 5) return;
        document.body.classList.add('y5-mode-active');
        injectY5MetallicNaskhStyles();

        const wIdx = (typeof playWeek !== 'undefined' ? playWeek : 1) - 1;
        const colIdx = Math.floor(wIdx / 4) % METALLIC_PALETTE.length;
        const pal = METALLIC_PALETTE[colIdx];
        document.documentElement.style.setProperty('--y5-week-spectrum', pal.border);
        document.documentElement.style.setProperty('--y5-week-shadow', pal.shadow);
    }

    function hookYear5Engine() {
        if (typeof RAW_YEAR === 'undefined' || RAW_YEAR !== 5) return;
        if (window._y5CleanHooked || typeof window.renderCurrentStep !== 'function') return;
        window._y5CleanHooked = true;
        applyY5MetallicThemeForCurrentWeek();

        const origRender = window.renderCurrentStep;
        window.renderCurrentStep = function() {
            applyY5MetallicThemeForCurrentWeek();
            origRender.apply(this, arguments);

            const defData = (typeof getActiveCurriculumObj === 'function') ? getActiveCurriculumObj() : null;
            if (!defData) return;

            if (globalStep === 0 && defData.learn?.introTTS && typeof speakText === 'function') {
                speakText(defData.learn.introTTS, () => {
                    if (typeof updateNavButtons === 'function') updateNavButtons(true);
                    if (typeof showCenterAction === 'function') showCenterAction(() => handleNextClick(), false);
                });
            } else if (globalStep === 2 && typeof currentQuestionIdx !== 'undefined') {
                const activeQ = defData.play?.questions?.[currentQuestionIdx];
                if (activeQ?.tts && typeof speakText === 'function') {
                    speakText(activeQ.tts);
                }
            } else if (globalStep === 5 && defData.apply?.applyTTS && typeof speakText === 'function') {
                speakText(defData.apply.applyTTS, () => {
                    if (typeof updateNavButtons === 'function') updateNavButtons(true);
                    if (typeof showCenterAction === 'function') showCenterAction(() => completeLesson(activeViewSubj), true);
                });
            }
        };
    }

    if (document.readyState === 'loading') {
        window.addEventListener('DOMContentLoaded', hookYear5Engine);
    } else {
        setTimeout(hookYear5Engine, 0);
    }
