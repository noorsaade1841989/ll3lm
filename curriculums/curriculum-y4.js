    function setupTracingCanvas(canvasEl, strokeColor, onStrokeDone) {
        const ctx = canvasEl.getContext('2d');
        const resize = () => {
            const rect = canvasEl.getBoundingClientRect();
            canvasEl.width = rect.width || 240;
            canvasEl.height = rect.height || 185;
            ctx.lineCap = 'round';
            ctx.lineJoin = 'round';
            ctx.lineWidth = 14;
            ctx.strokeStyle = strokeColor || '#e11d48';
        };
        setTimeout(resize, 30);

        let drawing = false;
        let pointsDrawn = 0;

        const getPos = (e) => {
            const rect = canvasEl.getBoundingClientRect();
            return { x: e.clientX - rect.left, y: e.clientY - rect.top };
        };

        canvasEl.onpointerdown = (e) => {
            if (typeof isSecretEditMode !== 'undefined' && isSecretEditMode) return;
            drawing = true;
            canvasEl.setPointerCapture(e.pointerId);
            const p = getPos(e);
            ctx.beginPath();
            ctx.moveTo(p.x, p.y);
        };
        canvasEl.onpointermove = (e) => {
            if (!drawing) return;
            e.preventDefault();
            const p = getPos(e);
            ctx.lineTo(p.x, p.y);
            ctx.stroke();
            pointsDrawn++;
        };
        canvasEl.onpointerup = canvasEl.onpointercancel = () => {
            if (!drawing) return;
            drawing = false;
            if (pointsDrawn > 8 && onStrokeDone) onStrokeDone();
        };

        return () => {
            ctx.clearRect(0, 0, canvasEl.width, canvasEl.height);
            pointsDrawn = 0;
        };
    }

